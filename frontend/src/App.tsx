const tokenA_ADDRESS = "0x75178E7AFA1a3e2d8ea5102862f43E324F1eC139";
const tokenB_ADDRESS = "0xe5EA2551A2f94A40c20E523C43339e5C240b355e";
const dex_ADDRESS = "0x5B9e99606552A0c6299aA03Fa6Dc35cfDAfB9a46";

function App() {
  const [account, setAccount] = useState("");
  const [web3, setWeb3] = useState<any>(null);
  const [amount, setAmount] = useState("100");

  const connectWallet = async () => {
    if ((window as any).ethereum) {
      try {
        const accounts = await (window as any).ethereum.request({ method: 'eth_requestAccounts' });
        const web3Instance = new Web3((window as any).ethereum);
        setWeb3(web3Instance);
        setAccount(accounts[0]);
      } catch (error) { alert("连接失败"); }
    } else { alert("请安装 MetaMask 钱包！"); }
  };

  const claimTokens = async () => {
    try {
      const contractA = new web3.eth.Contract(tokenA_ABI, tokenA_ADDRESS);
      const contractB = new web3.eth.Contract(tokenB_ABI, tokenB_ADDRESS);
      await contractA.methods.faucet().send({ from: account });
      await contractB.methods.faucet().send({ from: account });
      alert("领取成功！");
    } catch (e) { alert("领取失败"); }
  };

  const approve = async () => {
    try {
      const contractA = new web3.eth.Contract(tokenA_ABI, tokenA_ADDRESS);
      const contractB = new web3.eth.Contract(tokenB_ABI, tokenB_ADDRESS);
      const bigAmount = web3.utils.toWei("1000", "ether");
      await contractA.methods.approve(dex_ADDRESS, bigAmount).send({ from: account });
      await contractB.methods.approve(dex_ADDRESS, bigAmount).send({ from: account });
      alert("授权成功！");
    } catch (e) { alert("授权失败"); }
  };

  const addLiquidity = async () => {
    try {
      const contract = new web3.eth.Contract(dex_ABI, dex_ADDRESS);
      const bigAmount = web3.utils.toWei(amount, "ether");
      await contract.methods.addLiquidity(bigAmount, bigAmount).send({ from: account });
      alert("加池子成功！请去 MetaMask 查看你的 NFT 凭证。");
    } catch (e) { alert("加池子失败"); }
  };

  const swap = async () => {
    try {
      const contract = new web3.eth.Contract(dex_ABI, dex_ADDRESS);
      const bigAmount = web3.utils.toWei(amount, "ether");
      await contract.methods.swapAForB(bigAmount).send({ from: account });
      alert("交易成功！");
    } catch (e) { alert("交易失败"); }
  };

  return (
    <div style={{ padding: '50px', fontFamily: 'Arial' }}>
      <h1>我的去中心化交易所 (DEX)</h1>
      <button onClick={connectWallet} style={{ padding: '10px' }}>
        {account ? `已连接: ${account.slice(0,6)}...` : "连接 MetaMask 钱包"}
      </button>
      <div style={{ marginTop: '30px' }}>
        <button onClick={claimTokens} style={{ marginRight: '10px' }}>1. 领取测试币</button>
        <button onClick={approve}>2. 授权 DEX 使用代币</button>
      </div>
      <div style={{ marginTop: '20px' }}>
        <input type="number" value={amount} onChange={(e) => setAmount(e.target.value)} style={{ padding: '5px', width: '100px', marginRight: '10px' }} />
        <span>数量 (TokenA)</span>
      </div>
      <div style={{ marginTop: '20px' }}>
        <button onClick={addLiquidity} style={{ marginRight: '10px' }}>3. 添加流动性 (A+B)</button>
        <button onClick={swap}>4. 交易 (A 换 B)</button>
      </div>
    </div>
  );
}

export default App;
